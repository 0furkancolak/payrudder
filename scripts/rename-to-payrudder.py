#!/usr/bin/env python3
"""Mechanical rename quotify -> payrudder over the whole repository (phase 48, ADR 0022).

Run from the repository root on a clean checkout of main:

    python3 scripts/rename-to-payrudder.py        # rename paths and contents
    make gen                                       # regenerate protobuf and sqlc code (needs the tools: make tools)

Run it on a fresh checkout of main, then apply the hand-written follow-up (config fallback, ADR). It is not meant to be re-run over that follow-up, because it would rewrite the deliberate QUOTIFY_ fallback; when main moves, redo both steps from the new main.

What it renames: Go module paths, proto packages, binaries and commands, directories and files, Helm charts, compose and Kubernetes names, QUOTIFY_ environment
variables, metric names, dev database, role and bucket names, header names, docs and web package names (case kept: quotify, Quotify, QUOTIFY).

What it keeps (data and wire values that already exist in databases and at payment providers):
  * applied migrations (services/*/migrations, tools/*/migrations) are not edited;
  * the columns, JSON and provider custom-data keys quotify_subscription_id, quotify_plan_code, quotify_customer_id, quotify_migration_id;
  * the subscription owner value "quotify" (a stored value and an API enum) in the services, API and proto;
  * this script, the brand test that looks for the old name, the phase 48 plan and the brand folder.
"""
import os
import re
import subprocess
import sys

KEEP_PATH_PREFIXES = ("payrudder-brand/", "docs/adr/0021-payrudder-surface-rename.md", "docs/phases/phase-48-", "scripts/rename-to-payrudder.py", "tests/brand_test.go", ".git/")
KEEP_PATH_PARTS = ("/migrations/",)
OWNER_DIRS = ("services/plans-svc/", "services/payments-worker/", "services/billing-svc/", "services/gateway/", "pkg/payments/", "proto/", "web/admin/src/")
ALWAYS_KEEP = [
    re.compile(r"quotify_(?:subscription_id|plan_code|customer_id|migration_id)"),
    re.compile(r"'quotify'"),
    re.compile(r"\[quotify, provider\]"),
]
OWNER_KEEP = [re.compile(r'"quotify"')]
WORDS = [("quotify", "payrudder"), ("Quotify", "Payrudder"), ("QUOTIFY", "PAYRUDDER")]


def sh(*args: str) -> str:
    return subprocess.check_output(args, text=True)


def tracked() -> list[str]:
    return [p for p in sh("git", "ls-files", "-z").split("\0") if p]


def kept(path: str) -> bool:
    return path.startswith(KEEP_PATH_PREFIXES) or any(part in "/" + path for part in KEEP_PATH_PARTS)


def main() -> int:
    if not os.path.isdir(".git") and not os.path.isfile(".git"):
        print("run from the repository root", file=sys.stderr)
        return 1

    # Generated code is regenerated by `make gen`, not rewritten: the protobuf descriptors carry the package name with its length.
    if os.path.isdir("gen/go/quotify"):
        subprocess.check_call(["git", "rm", "-rq", "gen/go/quotify"])
        subprocess.call(["rm", "-rf", "gen/go/quotify"])

    # Build artifacts that were committed by mistake.
    for p in tracked():
        if p.endswith(("cmd/gateway/gateway", "cmd/plans-svc/plans-svc")):
            subprocess.check_call(["git", "rm", "-q", p])

    # Paths first, so the contents are written to the final names.
    for p in tracked():
        if "quotify" in p and not kept(p):
            q = p.replace("quotify", "payrudder")
            os.makedirs(os.path.dirname(q) or ".", exist_ok=True)
            subprocess.check_call(["git", "mv", p, q])

    changed = 0
    for p in tracked():
        if kept(p) or not os.path.isfile(p) or os.path.islink(p):
            continue
        with open(p, "rb") as f:
            raw = f.read()
        if b"\0" in raw:
            continue
        try:
            text = raw.decode("utf-8")
        except UnicodeDecodeError:
            continue
        if not re.search("quotify", text, re.I):
            continue
        keeps: list[str] = []

        def mask(m: re.Match) -> str:
            keeps.append(m.group(0))
            return f"\x01{len(keeps) - 1}\x02"

        out = text
        patterns = list(ALWAYS_KEEP) + (OWNER_KEEP if p.startswith(OWNER_DIRS) and not p.endswith((".yaml", ".yml")) else [])
        for pat in patterns:
            out = pat.sub(mask, out)
        for old, new in WORDS:
            out = out.replace(old, new)
        out = re.sub("\x01(\\d+)\x02", lambda m: keeps[int(m.group(1))], out)
        if out != text:
            with open(p, "w", encoding="utf-8") as f:
                f.write(out)
            changed += 1
    print(f"rewrote {changed} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
