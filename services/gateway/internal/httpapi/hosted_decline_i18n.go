// declineText is the sentence for a decline code, in the language of l. A code may carry detail after a colon ("buyer_incomplete:phone,tax_id"), which is the seller's to
// read, not the payer's. A code with no sentence of its own reads as decl_other, and an empty code is no reason at all.
func declineText(l map[string]string, code string) string {
	word, _, _ := strings.Cut(code, ":")
	if word == "" {
		return ""
	}
	if s := l["decl_"+word]; s != "" {
		return s
	}
	return l["decl_other"]
}
