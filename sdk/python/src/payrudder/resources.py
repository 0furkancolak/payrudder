    def __init__(self, client: AsyncPayrudder) -> None:
        self._client = client

    async def ingest_events(self, body: m.IngestEventsRequest, *, options: RequestOptions | None = None) -> m.IngestEventsResponse:
        """Ingest usage events (1..500 per request, at most 1 MiB).

        ``POST /v1/events``
        """
        return cast("m.IngestEventsResponse", await self._client._request("POST", "/v1/events", body=body, options=options))

    async def ingest(self, events: Sequence[m.IncomingEvent], *, options: RequestOptions | None = None) -> list[m.EventResult]:
        """Send any number of events: split into valid batches (1..500 events, under 1 MiB), fill a missing
        ``idempotency_key`` once (so automatic retries of a batch are safe), and return one result per event in
        input order. A rejected event is a result with ``status == "rejected"``, not an exception; a failed batch
        raises the usual error."""
        results: list[m.EventResult] = []
        for batch in prepare_ingest_batches(events):
            response = await self.ingest_events({"events": batch}, options=options)
            results.extend(response.get("results", []))
        return results


