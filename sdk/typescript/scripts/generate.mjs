// Generates src/generated/* from api/openapi/v1.yaml (tenant API: /v1/* only).
//
//   node scripts/generate.mjs           write the files
//   node scripts/generate.mjs --check   fail when the files on disk are stale
//
// The generator is plain JavaScript on purpose: it has one dependency (`yaml`) and runs on any Node the SDK supports.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import YAML from "yaml";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");
const specPath = path.resolve(root, "../../api/openapi/v1.yaml");

const METHODS = ["get", "post", "put", "patch", "delete"];
// Spec schema names that would clash with hand-written exports or DOM globals.
const RENAME = { Error: "ErrorEnvelope", WebhookEvent: "WebhookEventBody" };
// Namespaces whose generated class is extended by hand-written code (see src/events.ts).
const CUSTOM = new Set(["events"]);
const HEADER = `// Code generated by scripts/generate.mjs from api/openapi/v1.yaml. DO NOT EDIT.\n`;

const pascal = (s) =>
  s
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((w) => w[0].toUpperCase() + w.slice(1))
    .join("");
const camel = (s) => {
  const p = pascal(s);
  return p[0].toLowerCase() + p.slice(1);
};
const tsName = (n) => RENAME[n] ?? n;
const IDENT = /^[A-Za-z_$][A-Za-z0-9_$]*$/;
const key = (k) => (IDENT.test(k) ? k : JSON.stringify(k));

function doc(text, indent = "") {
  if (!text) return "";
  const lines = String(text)
    .replace(/\*\//g, "*\\/")
    .split("\n")
    .map((l) => l.trim())
    .filter((l, i, a) => l !== "" || (i > 0 && a[i - 1] !== ""));
  if (lines.length === 1) return `${indent}/** ${lines[0]} */\n`;
  return `${indent}/**\n${lines.map((l) => `${indent} * ${l}`.trimEnd()).join("\n")}\n${indent} */\n`;
}

export function generate(specText) {
  const spec = YAML.parse(specText);
  // The spec says "int64 as a string" in prose but often omits `format: int64`; every `*_minor` amount and every field
  // described as int64 must be treated as one, so a bigint can be passed and a number is never produced.
  (function mark(node) {
    if (Array.isArray(node)) return node.forEach(mark);
    if (!node || typeof node !== "object") return;
    if (node.properties) {
      for (const [k, v] of Object.entries(node.properties)) {
        if (v && !v.$ref && !v.format && (v.type === "string" || v.type === "integer") && (k.endsWith("_minor") || /\bint64\b/i.test(v.description ?? ""))) {
          v.format = "int64";
        }
      }
    }
    Object.values(node).forEach(mark);
  })(spec);
  const schemas = spec.components.schemas;
  const warnings = [];

  const refName = (r) => r.split("/").pop();
  const resolveParam = (p) => (p.$ref ? spec.components.parameters[refName(p.$ref)] : p);

  // --- which schemas carry int64 (so they need a *Params twin that accepts bigint) ---
  const int64Memo = new Map();
  function hasInt64(s) {
    if (!s || typeof s !== "object") return false;
    if (s.$ref) {
      const n = refName(s.$ref);
      if (int64Memo.has(n)) return int64Memo.get(n);
      int64Memo.set(n, false); // cycle guard
      const v = hasInt64(schemas[n]);
      int64Memo.set(n, v);
      return v;
    }
    if (isInt64(s)) return true;
    for (const k of ["allOf", "oneOf", "anyOf"]) if (s[k]?.some(hasInt64)) return true;
    if (s.items && hasInt64(s.items)) return true;
    if (s.properties && Object.values(s.properties).some(hasInt64)) return true;
    if (typeof s.additionalProperties === "object" && hasInt64(s.additionalProperties)) return true;
    return false;
  }
  const isInt64 = (s) => s.format === "int64" && (s.type === "integer" || s.type === "string");

  // --- schema -> TypeScript ---
  const nameFor = (n, mode) => tsName(n) + (mode === "input" && hasInt64({ $ref: `#/${n}` }) ? "Params" : "");

  function tsType(s, mode, lvl) {
    if (s === true || !s) return "unknown";
    let t = base(s, mode, lvl);
    if (s.nullable) t = `${t} | null`;
    return t;
  }
  const paren = (t) => (t.includes(" | ") && !t.startsWith("(") ? `(${t})` : t);

  function base(s, mode, lvl) {
    if (s.$ref) return nameFor(refName(s.$ref), mode);
    if (s.allOf) return s.allOf.map((x) => paren(tsType(x, mode, lvl))).join(" & ");
    const one = s.oneOf ?? s.anyOf;
    if (one) {
      // The ingest `quantity` is a decimal string or a JSON number; the SDK never produces floats, so only the string form is typed.
      if (one.length === 2 && one.some((x) => x.type === "string") && one.some((x) => x.type === "number")) return "string";
      return one.map((x) => tsType(x, mode, lvl)).join(" | ");
    }
    if (Array.isArray(s.type)) return s.type.map((t) => (t === "null" ? "null" : tsType({ ...s, type: t }, mode, lvl))).join(" | ");
    if (s.enum) return s.enum.map((v) => (v === null ? "null" : JSON.stringify(v))).join(" | ");
    switch (s.type) {
      case "string":
        return isInt64(s) ? (mode === "input" ? "Int64Input" : "Int64") : "string";
      case "integer":
        return isInt64(s) ? (mode === "input" ? "Int64Input" : "Int64") : "number";
      case "number":
        return "number";
      case "boolean":
        return "boolean";
      case "null":
        return "null";
      case "array":
        return `Array<${tsType(s.items, mode, lvl)}>`;
      case "object":
      case undefined:
        return objectType(s, mode, lvl);
      default:
        throw new Error(`unsupported schema type ${s.type}`);
    }
  }

  function objectType(s, mode, lvl) {
    const props = s.properties;
    const ap = s.additionalProperties;
    if (!props) {
      if (ap && ap !== true) return `Record<string, ${tsType(ap, mode, lvl)}>`;
      return s.type === "object" || ap ? "Record<string, unknown>" : "unknown";
    }
    const pad = "  ".repeat(lvl + 1);
    const required = new Set(s.required ?? []);
    const lines = Object.entries(props).map(([k, v]) => {
      const d = v && !v.$ref && v.description ? doc(v.description, pad) : "";
      return `${d}${pad}${key(k)}${required.has(k) ? "" : "?"}: ${tsType(v, mode, lvl + 1)};`;
    });
    return `{\n${lines.join("\n")}\n${"  ".repeat(lvl)}}`;
  }

  // --- collect operations ---
  const ops = [];
  for (const [p, item] of Object.entries(spec.paths)) {
    if (!p.startsWith("/v1/")) continue;
    for (const m of METHODS) {
      const op = item[m];
      if (!op) continue;
      ops.push({ path: p, method: m.toUpperCase(), op, item });
    }
  }

  const inlineTypes = []; // [name, schema, mode]
  const reachable = new Set();
  function reach(s) {
    if (!s || typeof s !== "object") return;
    if (s.$ref) {
      const n = refName(s.$ref);
      if (reachable.has(n)) return;
      reachable.add(n);
      reach(schemas[n]);
      return;
    }
    for (const k of ["allOf", "oneOf", "anyOf"]) s[k]?.forEach(reach);
    reach(s.items);
    if (s.properties) Object.values(s.properties).forEach(reach);
    if (typeof s.additionalProperties === "object") reach(s.additionalProperties);
  }

  const resources = new Map(); // ns -> methods[]
  const paged = [];

  for (const { path: p, method, op, item } of ops) {
    const id = op.operationId;
    if (!id) throw new Error(`${method} ${p} has no operationId`);
    const P = pascal(id);
    const ns = camel(p.split("/")[2]);
    const params = [...(item.parameters ?? []), ...(op.parameters ?? [])].map(resolveParam);

    const pathNames = [...p.matchAll(/\{([^}]+)\}/g)].map((x) => x[1]);
    const pathParams = pathNames.map((n) => {
      const d = params.find((x) => x.in === "path" && x.name === n);
      if (!d) throw new Error(`${id}: path param ${n} not declared`);
      return d;
    });
    const queryParams = params.filter((x) => x.in === "query");
    const headerParams = params.filter((x) => x.in === "header");

    const args = [];
    for (const d of pathParams) args.push({ name: camel(d.name), type: tsType(d.schema, "input", 0), required: true, path: d.name });

    // request body
    let bodyKind;
    if (op.requestBody) {
      const content = op.requestBody.content;
      const mt = Object.keys(content)[0];
      let type;
      if (mt === "application/json") {
        bodyKind = "json";
        const sc = content[mt].schema;
        if (sc.$ref) {
          reach(sc);
          type = nameFor(refName(sc.$ref), "input");
        } else {
          reach(sc);
          type = `${P}Request`;
          inlineTypes.push([type, sc, "input"]);
        }
      } else if (mt === "multipart/form-data") {
        bodyKind = "form";
        type = "FormData";
      } else throw new Error(`${id}: unsupported request media type ${mt}`);
      args.push({ name: "body", type, required: !!op.requestBody.required });
    }

    let queryType;
    if (queryParams.length) {
      queryType = `${P}Query`;
      inlineTypes.push([
        queryType,
        {
          type: "object",
          required: queryParams.filter((q) => q.required).map((q) => q.name),
          properties: Object.fromEntries(
            queryParams.map((q) => [q.name, { ...q.schema, description: q.description ?? q.schema?.description }]),
          ),
        },
        "input",
      ]);
      args.push({ name: "query", type: queryType, required: queryParams.some((q) => q.required) });
    }

    // response
    const okCode = Object.keys(op.responses).find((c) => c.startsWith("2"));
    const ok = op.responses[okCode];
    let response = "none";
    let resType = "void";
    let resSchema;
    if (ok.content) {
      const mt = Object.keys(ok.content)[0];
      if (mt === "application/json") {
        response = "json";
        const sc = ok.content[mt].schema;
        resSchema = sc.$ref ? schemas[refName(sc.$ref)] : sc;
        reach(sc);
        if (sc.$ref) resType = nameFor(refName(sc.$ref), "output");
        else {
          resType = `${P}Response`;
          inlineTypes.push([resType, sc, "output"]);
        }
      } else if (mt === "text/csv") {
        response = "text";
        resType = "string";
      } else {
        response = "bytes";
        resType = "Uint8Array";
      }
    }

    // arguments after the last required one must be required themselves
    const lastReq = args.map((a) => a.required).lastIndexOf(true);
    const sig = args.map((a, i) =>
      i < lastReq && !a.required ? `${a.name}: ${a.type} | undefined` : `${a.name}${a.required ? "" : "?"}: ${a.type}`,
    );
    sig.push("options?: RequestOptions");

    const idemHeader = headerParams.some((h) => h.name.toLowerCase() === "idempotency-key");
    const url = "`" + p.replace(/\{([^}]+)\}/g, (_, n) => `\${seg(${camel(n)})}`) + "`";
    const spec2 = [`method: "${method}"`, `path: ${url}`];
    if (queryType) spec2.push("query");
    if (op.requestBody) spec2.push("body", `bodyKind: "${bodyKind}"`);
    spec2.push(`response: "${response}"`);
    if (idemHeader) spec2.push("idempotencyHeader: true");

    const description = [op.summary, op.description].filter(Boolean).join("\n\n") + `\n\n\`${method} ${p}\``;
    const code =
      doc(description, "  ") +
      `  ${id}(${sig.join(", ")}): Promise<${resType}> {\n` +
      `    return this.t.request<${resType}>({ ${spec2.join(", ")} }, options);\n  }\n`;
    if (!resources.has(ns)) resources.set(ns, []);
    resources.get(ns).push({ id, code });

    // pagination
    if (queryParams.some((q) => q.name === "page_token") && resSchema?.properties?.next_page_token && !op.requestBody) {
      // A side array of aggregates (`totals`) is not the page's items.
      const arrays = Object.entries(resSchema.properties).filter(([k, v]) => v.type === "array" && !/^totals?$/.test(k));
      if (arrays.length !== 1) warnings.push(`${id}: expected exactly one array property in the paged response, found ${arrays.length}`);
      else {
        const callArgs = args.filter((a) => a.name !== "query").map((a) => a.name);
        paged.push({ id, ns, sig, args, resType, field: arrays[0][0], callArgs, hasQuery: !!queryType });
      }
    }
  }

  // --- types.ts ---
  const decl = [];
  const emitted = new Set();
  const twins = new Set();
  function emitSchema(name, s, mode) {
    const out = name;
    if (emitted.has(out)) return;
    emitted.add(out);
    const t = tsType(s, mode, 0);
    const d = s.description ? doc(s.description) : "";
    if (t.startsWith("{") && !s.allOf && !s.oneOf && !s.nullable) decl.push(`${d}export interface ${out} ${t}\n`);
    else decl.push(`${d}export type ${out} = ${t};\n`);
  }

  for (const n of [...reachable].sort()) {
    emitSchema(tsName(n), schemas[n], "output");
    if (hasInt64({ $ref: `#/${n}` })) {
      twins.add(tsName(n) + "Params");
      emitSchema(tsName(n) + "Params", schemas[n], "input");
    }
  }
  for (const [n, s, mode] of inlineTypes) emitSchema(n, s, mode);
  decl.sort((a, b) => nameOf(a).localeCompare(nameOf(b)));
  function nameOf(d) {
    return /export (?:interface|type) (\w+)/.exec(d)[1];
  }

  // --- resources.ts ---
  const nsList = [...resources.keys()].sort();
  const className = (ns) => pascal(ns) + (CUSTOM.has(ns) ? "ResourceBase" : "Resource");
  let resBody = "";
  for (const ns of nsList) {
    resBody += `\nexport class ${className(ns)} {\n  constructor(private readonly t: Transport) {}\n\n`;
    resBody += resources
      .get(ns)
      .map((m) => m.code)
      .join("\n");
    resBody += `}\n`;
  }
  // Keep an `*Params` twin (the bigint-accepting variant of a type that holds int64) only when something references it (an output type never needs its twin).
  const declByName = new Map(decl.map((d) => [nameOf(d), d]));
  const keep = new Set([...declByName.keys()].filter((n) => !twins.has(n)));
  const inputRef = /\b(\w+Params)\b/g;
  const queue = [resBody, ...[...keep].map((n) => declByName.get(n))];
  while (queue.length) {
    for (const m of queue.pop().matchAll(inputRef)) {
      const n = m[1];
      if (declByName.has(n) && !keep.has(n)) {
        keep.add(n);
        queue.push(declByName.get(n));
      }
    }
  }
  const kept = decl.filter((d) => keep.has(nameOf(d)));
  const typesTs =
    HEADER +
    `import type { Int64, Int64Input } from "../int64";\n\n` +
    `export type { Int64, Int64Input };\n\n` +
    kept.join("\n");
  const usedTypes = [...keep].filter((n) => new RegExp(`\\b${n}\\b`).test(resBody)).sort();
  const resTs =
    HEADER +
    `import type { RequestOptions, Transport } from "../transport";\nimport { seg } from "../transport";\n` +
    `import type {\n${usedTypes.map((n) => `  ${n},`).join("\n")}\n} from "./types";\n` +
    resBody;

  // --- client-base.ts ---
  const custom = nsList.filter((n) => CUSTOM.has(n));
  const std = nsList.filter((n) => !CUSTOM.has(n));
  let base2 =
    HEADER +
    `import { paginate } from "../pagination";\nimport type { RequestOptions, Transport } from "../transport";\n` +
    `import { ${custom.map((n) => `${pascal(n)}Resource`).join(", ")} } from "../events";\n` +
    `import {\n${std.map((n) => `  ${className(n)},`).join("\n")}\n} from "./resources";\n` +
    `import type {\n${[...new Set([...paged.map((p) => p.resType), ...paged.flatMap((p) => (p.hasQuery ? [pascal(p.id) + "Query"] : []))])]
      .sort()
      .map((n) => `  ${n},`)
      .join("\n")}\n} from "./types";\n\n`;
  base2 += `/** Every operation of the tenant API as an async iterator over all pages (items, not pages). */\nexport class Paginators {\n  constructor(private readonly r: PayrudderResources) {}\n`;
  for (const pg of paged) {
    const item = `NonNullable<${pg.resType}["${pg.field}"]>[number]`;
    const qarg = pg.hasQuery ? `query?: ${pascal(pg.id)}Query` : null;
    const sigs = [...pg.args.filter((a) => a.name !== "query").map((a) => `${a.name}: ${a.type}`), qarg, "options?: RequestOptions"].filter(Boolean);
    const call = [...pg.callArgs, "q"].join(", ");
    base2 +=
      `\n  ${pg.id}(${sigs.join(", ")}): AsyncGenerator<${item}, void, undefined> {\n` +
      `    return paginate(\n      (q) => this.r.${pg.ns}.${pg.id}(${call}, options),\n      (page) => page.${pg.field},\n      ${pg.hasQuery ? "query" : "undefined"},\n    );\n  }\n`;
  }
  base2 += `}\n\n`;
  base2 += `/** The resource namespaces of the client; \`Payrudder\` extends it. */\nexport abstract class PayrudderResources {\n`;
  for (const ns of nsList) base2 += `  readonly ${ns}: ${pascal(ns)}Resource;\n`;
  base2 += `  /** Async iterators that walk every page of a list operation. */\n  readonly paginate: Paginators;\n\n  constructor(t: Transport) {\n`;
  for (const ns of nsList) base2 += `    this.${ns} = new ${pascal(ns)}Resource(t);\n`;
  base2 += `    this.paginate = new Paginators(this);\n  }\n}\n`;

  return {
    files: {
      "src/generated/types.ts": typesTs,
      "src/generated/resources.ts": resTs,
      "src/generated/client-base.ts": base2,
    },
    warnings,
    stats: { operations: ops.length, namespaces: nsList.length, paginated: paged.map((p) => p.id) },
  };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { files, warnings, stats } = generate(fs.readFileSync(specPath, "utf8"));
  for (const w of warnings) console.warn(`warning: ${w}`);
  const check = process.argv.includes("--check");
  let stale = false;
  for (const [rel, content] of Object.entries(files)) {
    const abs = path.join(root, rel);
    if (check) {
      if (!fs.existsSync(abs) || fs.readFileSync(abs, "utf8") !== content) {
        console.error(`stale: ${rel} (run npm run generate)`);
        stale = true;
      }
    } else {
      fs.mkdirSync(path.dirname(abs), { recursive: true });
      fs.writeFileSync(abs, content);
    }
  }
  if (stale) process.exit(1);
  console.log(`${check ? "checked" : "generated"} ${stats.operations} operations, ${stats.namespaces} namespaces, ${stats.paginated.length} paginated`);
}
